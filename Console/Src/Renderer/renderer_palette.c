#include "Renderer/renderer.h"
#include <stdint.h>

/* Pixel Forge's 64-color system palette (pixelforge/palette.py) as RGB565.
 * Assets store palette entries as indices into this table; this is where they
 * become panel colors. Generated from the same source as the editor. Split out of
 * the (-O3, per-frame) renderer TU since it is pure data, referenced only by the
 * cold rendererSystemColor() lookup games issue to resolve a system-palette index. */
static const uint16_t s_system_palette[64] = {
    0x630C, 0x0173, 0x0898, 0x3818, 0x6013, 0x7809, 0x7800, 0x60C0,
    0x39A0, 0x0A60, 0x02C0, 0x02C0, 0x0249, 0x0000, 0x0000, 0x0000,
    0xAD55, 0x033E, 0x31FF, 0x70DF, 0xA85E, 0xC871, 0xC903, 0xAA20,
    0x7360, 0x3380, 0x0500, 0x04E3, 0x0451, 0x0000, 0x0000, 0x0000,
    0xFFFF, 0x4DBF, 0x847F, 0xCB5F, 0xFADF, 0xFAFC, 0xFB8D, 0xFCC0,
    0xCE00, 0x8700, 0x4FA0, 0x2F8D, 0x2EDC, 0x4A69, 0x0000, 0x0000,
    0xFFFF, 0xBFFF, 0xCE9F, 0xEE3F, 0xFDFF, 0xFDFE, 0xFE38, 0xFEB3,
    0xEF30, 0xCF90, 0xBFD3, 0xAFD8, 0xAF9E, 0xBDD7, 0x0000, 0x0000,
};

uint16_t rendererSystemColor(uint8_t system_index)
{
    return s_system_palette[system_index & 0x3FU];
}
